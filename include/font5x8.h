#pragma once

#include <Arduino.h>

// Minimal 5x8 pixel font (bit 7 = leftmost column, row 7 is a blank spacer
// row used as inter-character gap). Only the glyphs needed for "HELLO WORLD"
// are defined; unknown characters fall back to a blank space.
#define FONT_WIDTH 5
#define FONT_HEIGHT 8

struct Glyph {
  char c;
  uint8_t rows[FONT_HEIGHT];
};

static const Glyph FONT_GLYPHS[] = {
    {'H', {0x88, 0x88, 0x88, 0xF8, 0x88, 0x88, 0x88, 0x00}},
    {'E', {0xF8, 0x80, 0x80, 0xF0, 0x80, 0x80, 0xF8, 0x00}},
    {'L', {0x80, 0x80, 0x80, 0x80, 0x80, 0x80, 0xF8, 0x00}},
    {'O', {0x70, 0x88, 0x88, 0x88, 0x88, 0x88, 0x70, 0x00}},
    {'W', {0x88, 0x88, 0x88, 0xA8, 0xA8, 0xD8, 0x88, 0x00}},
    {'R', {0xF0, 0x88, 0x88, 0xF0, 0xA0, 0x90, 0x88, 0x00}},
    {'D', {0xF0, 0x88, 0x88, 0x88, 0x88, 0x88, 0xF0, 0x00}},
    {' ', {0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00}},
};

inline const Glyph *findGlyph(char c) {
  for (const Glyph &g : FONT_GLYPHS) {
    if (g.c == c) {
      return &g;
    }
  }
  // fall back to space for anything not in the small table above
  return &FONT_GLYPHS[sizeof(FONT_GLYPHS) / sizeof(FONT_GLYPHS[0]) - 1];
}
