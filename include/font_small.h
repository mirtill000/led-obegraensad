inline const Glyph *findGlyph(char c) {
  if (c >= 'A' && c <= 'Z') c = c - 'A' + 'a';
  for (const Glyph &g : FONT_GLYPHS) {
    if (g.c == c) {
      return &g;
    }
  }
  // fall back to space for anything not in the table above
  return &FONT_GLYPHS[0];
}
