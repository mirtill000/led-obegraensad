inline const TinyGlyph *findTinyGlyph(char c) {
  if (c >= 'a' && c <= 'z') c = c - 'a' + 'A';
  const TinyGlyph *space = nullptr;
  for (const TinyGlyph &g : TINY_GLYPHS) {
    if (g.c == c) return &g;
    if (g.c == ' ') space = &g;
  }
  return space;
}
