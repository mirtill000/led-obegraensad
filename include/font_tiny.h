#pragma once

#include <Arduino.h>

// "Tiny" font: capitals only, 4 rows tall - the smallest that stays
// readable, so that three lines fit on the panel (4+1+4+1+4 = 14 rows).
// Letters are 3 pixels wide (M, W 5, N 4); lowercase is drawn as capitals.
// With only 4 rows some shapes are close, so the ambiguous pairs are kept
// apart on purpose: O round and 0 square, S and 5, B and 8, Z and 2.
#define TINY_HEIGHT 4

struct TinyGlyph {
  char c;
  uint8_t width;
  uint8_t rows[TINY_HEIGHT];  // bit 7 = leftmost column
};

