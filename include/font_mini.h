inline const MiniGlyph *findMiniGlyph(char c) {
  // Accented lowercase (Latin-1, see Display::fontText) -> plain letter.
  switch ((uint8_t)c) {
    case 0xE0: c = 'a'; break;
    case 0xE8: case 0xE9: c = 'e'; break;
    case 0xEC: c = 'i'; break;
    case 0xF2: c = 'o'; break;
    case 0xF9: c = 'u'; break;
  }
  if (c >= 'a' && c <= 'z') c = c - 'a' + 'A';
  const MiniGlyph *space = nullptr;
  for (const MiniGlyph &g : MINI_GLYPHS) {
    if (g.c == c) return &g;
    if (g.c == ' ') space = &g;
  }
  return space;
}
